"""Evaluate FP.ai clause screening against a human-labelled JSONL dataset.

Expected JSONL fields per line:
  {"document_id": "doc-001", "clause_text": "...", "is_risky": true}

Clauses from the same source contract must share document_id so the
document-relative anomaly detector is evaluated in the same grouping it uses
at runtime. Labels must be reviewed by a qualified annotator. This script does
not create labels or claim legal accuracy.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from sklearn.metrics import confusion_matrix, precision_recall_fscore_support

BACKEND_DIR = Path(__file__).resolve().parents[1]
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.ml.engine import FPMLEngine


def load_records(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    with path.open(encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON on line {line_number}: {exc}") from exc
            if not isinstance(row.get("document_id"), str) or not row["document_id"].strip():
                raise ValueError(f"Line {line_number}: document_id is required.")
            if not isinstance(row.get("clause_text"), str) or not row["clause_text"].strip():
                raise ValueError(f"Line {line_number}: clause_text is required.")
            if not isinstance(row.get("is_risky"), bool):
                raise ValueError(f"Line {line_number}: is_risky must be a boolean human label.")
            records.append(row)

    if len(records) < 10:
        raise ValueError("At least 10 human-labelled clauses are required for an evaluation run.")
    if {row["is_risky"] for row in records} != {True, False}:
        raise ValueError("The dataset must contain both risky and non-risky clauses.")
    return records


def calculate_metrics(y_true: list[bool], y_pred: list[bool]) -> dict[str, Any]:
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="binary", zero_division=0
    )
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[False, True]).ravel()
    return {
        "precision": round(float(precision), 4),
        "recall": round(float(recall), 4),
        "f1": round(float(f1), 4),
        "confusion_matrix": {
            "true_negative": int(tn),
            "false_positive": int(fp),
            "false_negative": int(fn),
            "true_positive": int(tp),
        },
        "support": len(y_true),
    }


async def run_evaluation(path: Path) -> dict[str, Any]:
    records = load_records(path)
    engine = FPMLEngine()
    await engine.load()

    by_document: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        by_document[record["document_id"]].append(record)

    y_true: list[bool] = []
    rule_predictions: list[bool] = []
    hybrid_predictions: list[bool] = []

    for document_id, rows in by_document.items():
        clause_texts = [row["clause_text"] for row in rows]
        analysed = engine.analyze_clauses(clause_texts, document_id=document_id)
        for row, result in zip(rows, analysed):
            y_true.append(row["is_risky"])
            pattern, _, _ = engine._pattern_match(row["clause_text"])
            rule_predictions.append(bool(
                pattern and pattern.risk_level.value in ("critical", "high")
            ))
            hybrid_predictions.append(result.risk_level in ("critical", "high"))

    return {
        "dataset": str(path),
        "label_source": "human-supplied; not generated by FP.ai",
        "n_documents": len(by_document),
        "n_clauses": len(records),
        "risk_prevalence": round(sum(y_true) / len(y_true), 4),
        "rule_match_baseline": calculate_metrics(y_true, rule_predictions),
        "hybrid_screening": calculate_metrics(y_true, hybrid_predictions),
        "interpretation": (
            "Metrics measure agreement with this labelled sample only; "
            "they do not establish legal correctness or generalisation."
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate FP.ai on human-labelled clause data.")
    parser.add_argument("--input", required=True, type=Path, help="Path to human-labelled JSONL file.")
    args = parser.parse_args()
    result = asyncio.run(run_evaluation(args.input))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
